"""Character sets for text carried in the DAB signal (ETSI TS 101 756, table 1).

Dynamic labels, service and ensemble names and MOT file names carry a 4-bit character
set identifier. Exactly three values are registered:

* 0: the "Complete EBU Latin based repertoire" (Annex C), an 8-bit character set of its
  own that is neither ASCII nor Latin-1. German umlauts, for example, sit at 0x91 (ä),
  0x97 (ö), 0x99 (ü) and 0x8D (ß).
* 6: UTF-16, big endian, basic plane only (i.e. UCS-2).
* 15: UTF-8.

Confirmed on air (19 September 2026): Dlf sends "Büchermarkt" with 0x99 for the ü and
SCHLAGERPARADIES sends "MÜLLER" with 0xD9 for the Ü, both in character set 0. Latin-1
would have used 0xFC and 0xDC.
"""

from __future__ import annotations

CHARSET_EBU_LATIN = 0
CHARSET_UTF16 = 6
CHARSET_UTF8 = 15

# ETSI TS 101 756 V2.4.1, Annex C, table C.2: Unicode code point per byte, laid out
# like table C.1 (one row of the standard is two rows here). Read from the standard
# by machine and checked against the Unicode names given there. The only discrepancy
# in the standard: for 0xD3, table C.2 gives U+00CB but names it "A WITH DIAERESIS";
# table C.1 shows Ë there, so the number wins.
#
# None marks the codes 0x00, 0x0A, 0x0B and 0x1F: "reserved for future definition and
# are not displayed". In dynamic labels 0x0A, 0x0B and 0x1F mean line break, end of
# headline and preferred word break (ETSI EN 300 401, clause 7.4.5.2); they are not
# displayed there either.
#
# Beware, even the ASCII range deviates: 0x24 is ł (not $), 0x5C Ů, 0x5E Ł, 0x60 Ą,
# 0x7B-0x7F « ů » Ľ Ħ. The dollar sign lives at 0xAB.
