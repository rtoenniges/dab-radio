EBU_LATIN: tuple[str, ...] = tuple(
    "" if codepoint is None else chr(codepoint) for codepoint in _EBU_LATIN_CODEPOINTS
)


def decode_ebu_latin(raw: bytes) -> str:
    """Decodes bytes in the EBU Latin character set (Annex C)."""
    return "".join(EBU_LATIN[byte] for byte in raw)


def decode_charset(raw: bytes, charset: int) -> str:
    """Decodes text according to its character set identifier.

    Unregistered identifiers are not guessed: only printable ASCII survives, everything
    above it becomes "?".
    """
    if charset == CHARSET_EBU_LATIN:
        return decode_ebu_latin(raw)
    if charset == CHARSET_UTF8:
        return raw.decode("utf-8", errors="replace")
    if charset == CHARSET_UTF16:
        return raw.decode("utf-16-be", errors="replace")
    return "".join(chr(b) if 0x20 <= b <= 0x7E else ("?" if b > 0x7E else "") for b in raw)
